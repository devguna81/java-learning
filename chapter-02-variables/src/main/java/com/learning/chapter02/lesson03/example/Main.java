public class Main {

    public static void main(String[] args) {

        int maxInt = Integer.MAX_VALUE;
        System.out.println("int 최댓값: " + maxInt);

        long bigNumber = 10000000000L;
        System.out.println("long으로 저장한 큰 수: " + bigNumber);

    }
}
