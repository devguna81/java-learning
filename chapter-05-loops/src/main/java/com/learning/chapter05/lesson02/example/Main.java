package com.learning.chapter05.lesson02.example;

/**
 * [Chapter 05. 반복문]
 * 02. for - 예제 코드
 *
 * 블로그 원문: https://jqdom.com/blog/440
 */

public class Main {

    public static void main(String[] args) {

        for (int i = 1; i <= 3; i++) {
            System.out.println(i + "번째 몬스터를 공격합니다");
        }

        System.out.println("총 3마리를 공격했습니다");

    }
}
