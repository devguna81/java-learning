public class Main {

    public static void main(String[] args) {

        int hp = 45;

        System.out.println("hp == 45: " + (hp == 45));
        System.out.println("hp != 45: " + (hp != 45));
        System.out.println("hp < 50: " + (hp < 50));
        System.out.println("hp > 50: " + (hp > 50));
        System.out.println("hp <= 45: " + (hp <= 45));
        System.out.println("hp >= 100: " + (hp >= 100));

    }
}
